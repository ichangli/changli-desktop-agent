import { _electron as electron, expect } from '@playwright/test'
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
const dir = mkdtempSync(join(tmpdir(), 'changli-data-e2e-'))
const env = { ...process.env, CHANGLI_DATA_DIR: join(dir, 'data') }
delete env.ELECTRON_RUN_AS_NODE
let app
const errors = []
async function launch() {
  app = await electron.launch({ args: [resolve('out/main/index.js')], env })
  const page = await app.firstWindow()
  page.on('pageerror', error => errors.push(error.message))
  await page.getByRole('button', { name: '＋ 新的对话' }).waitFor()
  return page
}
const api = (page, method, value) => page.evaluate(({ method, value }) => window.changli[method](value), { method, value })
async function chooseSave(path, cancelled = false) { await app.evaluate(({ dialog }, { path, cancelled }) => { dialog.showSaveDialog = async () => ({ canceled: cancelled, filePath: path }) }, { path, cancelled }) }
async function chooseOpen(path, cancelled = false) { await app.evaluate(({ dialog }, { path, cancelled }) => { dialog.showOpenDialog = async () => ({ canceled: cancelled, filePaths: [path] }) }, { path, cancelled }) }
try {
  let page = await launch()
  await page.getByRole('textbox', { name: '消息', exact: true }).fill('雪落在山间，这是用于搜索的虚构内容')
  await page.getByRole('button', { name: '发送 ↑' }).click()
  await expect(page.getByRole('button', { name: '停止生成', exact: true })).toBeVisible()
  await expect(api(page, 'deleteConversation', (await api(page, 'snapshot')).selectedId)).rejects.toThrow(/停止生成/)
  await page.getByRole('button', { name: '停止生成', exact: true }).click()
  await expect(page.locator('.status').last()).toContainText('已停止')
  await page.getByRole('button', { name: '重命名会话', exact: true }).click()
  await page.getByRole('textbox', { name: '会话名称', exact: true }).fill('山间闲谈')
  await page.getByRole('button', { name: '保存名称', exact: true }).click()
  await expect(page.locator('nav button')).toHaveText('山间闲谈')
  const originalId = (await api(page, 'snapshot')).selectedId
  await page.getByRole('button', { name: '＋ 新的对话' }).click()
  await page.getByRole('textbox', { name: '搜索历史', exact: true }).fill('雪落')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.locator('nav button')).toHaveCount(1)
  await page.locator('nav button').click()
  await expect(page.locator('.search-match')).toContainText('雪落')
  expect((await api(page, 'snapshot')).selectedId).toBe(originalId)
  await api(page, 'saveMemory', { content: '虚构偏好：简短', category: 'fact' })
  const exported = join(dir, 'chat.md'), backup = join(dir, 'backup.json')
  await chooseSave(exported)
  await page.getByRole('button', { name: '导出聊天', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('文件已保存。')
  expect(readFileSync(exported, 'utf8')).toContain('山间闲谈')
  expect(readFileSync(exported, 'utf8')).toContain('已停止')
  await page.getByRole('button', { name: '数据管理', exact: false }).click()
  await chooseSave(backup)
  await page.getByRole('button', { name: '备份聊天与记忆', exact: true }).click()
  await expect.poll(() => { try { return JSON.parse(readFileSync(backup, 'utf8')).messages.length } catch { return 0 } }).toBe(2)
  const data = JSON.parse(readFileSync(backup, 'utf8'))
  expect(Object.keys(data)).toEqual(['format', 'version', 'createdAt', 'conversations', 'messages', 'memories'])
  await chooseSave(join(dir, 'cancelled.json'), true)
  await page.getByRole('button', { name: '备份聊天与记忆', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('已取消')
  expect(existsSync(join(dir, 'cancelled.json'))).toBe(false)
  await chooseSave(join(dir, 'missing-parent', 'fail.json'))
  await page.getByRole('button', { name: '备份聊天与记忆', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('文件写入失败，请检查保存位置和磁盘空间。')
  const bad = join(dir, 'bad.json'); writeFileSync(bad, '{bad')
  await chooseOpen(bad)
  await page.getByRole('button', { name: '选择备份恢复', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('备份格式无效')
  await chooseOpen(backup)
  await page.getByRole('button', { name: '选择备份恢复', exact: true }).click()
  await expect(page.getByRole('button', { name: '确认导入副本', exact: true })).toBeVisible()
  expect((await api(page, 'snapshot')).conversations.length).toBe(2)
  await page.getByRole('button', { name: '取消恢复', exact: true }).click()
  await expect(api(page, 'restoreData', 'stale')).rejects.toThrow(/已失效/)
  await page.getByRole('button', { name: '选择备份恢复', exact: true }).click()
  await page.getByRole('button', { name: '确认导入副本', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('已恢复 2 段会话、2 条消息和 0 条新记忆')
  expect((await api(page, 'snapshot')).conversations.length).toBe(4)
  await page.getByRole('button', { name: '选择备份恢复', exact: true }).click()
  await page.getByRole('button', { name: '确认导入副本', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('已经恢复过')
  await page.getByRole('button', { name: '取消恢复', exact: true }).click()
  await page.getByRole('button', { name: '清除', exact: true }).click()
  await page.locator('nav button').filter({ hasText: '山间闲谈' }).first().click()
  await page.getByRole('button', { name: '删除会话', exact: true }).click()
  await page.getByRole('button', { name: '保留会话', exact: true }).click()
  expect((await api(page, 'snapshot')).conversations.length).toBe(4)
  await page.getByRole('button', { name: '删除会话', exact: true }).click()
  await page.getByRole('button', { name: '确认删除会话', exact: true }).click()
  await expect.poll(async () => (await api(page, 'snapshot')).conversations.length).toBe(3)
  expect((await api(page, 'workspace')).memories.length).toBe(1)
  await app.close(); page = await launch()
  expect((await api(page, 'snapshot')).conversations.length).toBe(3)
  await expect(page.locator('nav button').filter({ hasText: '山间闲谈' })).toHaveCount(1)
  mkdirSync('test-results', { recursive: true })
  await page.locator('nav button').filter({ hasText: '山间闲谈' }).click()
  await page.screenshot({ path: 'test-results/data-management-chat.png' })
  await page.getByRole('button', { name: '数据管理', exact: false }).click()
  await page.screenshot({ path: 'test-results/data-management-backup.png' })
  expect(errors).toEqual([])
  console.log('数据管理 Electron 回归通过：改名/正文搜索定位/导出/备份/取消/损坏拒绝/确认恢复/去重/删除/重启。仅使用临时数据与原生对话框桩。')
} finally {
  await app?.close().catch(() => {})
  if (!dir.startsWith(join(tmpdir(), 'changli-data-e2e-'))) throw new Error('临时目录校验失败')
  rmSync(dir, { recursive: true, force: true })
}
