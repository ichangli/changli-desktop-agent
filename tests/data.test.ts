import { test } from 'node:test'
import assert from 'node:assert/strict'
import { Store } from '../src/main/store'
import { makeBackup, parseBackup, restoreBackup, conversationMarkdown } from '../src/main/data'

function fixture() {
  const store = new Store(':memory:')
  const id = store.create()
  const message = store.add(id, 'user', '正文关键字：雪落', 'complete')
  store.add(id, 'assistant', '尚未完成', 'generating')
  store.saveMemory({ content: '喜欢简短回答', category: 'fact', source: '会话消息：' + message.id })
  return { store, id, message }
}
test('会话改名、正文/名称字面搜索、导出状态及删除关联记录', () => {
  const { store, id } = fixture()
  store.renameConversation(id, '我的名称 100%_')
  assert.equal(store.search('雪落')[0].sessionId, id)
  assert.equal(store.search('100%_').length, 1)
  assert.equal(store.search('%').length, 1)
  assert.equal(store.search('不匹配').length, 0)
  assert.equal(store.search(' ').length, 0)
  assert.throws(() => store.renameConversation(id, ' '))
  assert.throws(() => store.renameConversation(id, '长'.repeat(81)))
  assert.throws(() => store.renameConversation('unknown', 'a'))
  assert.match(conversationMarkdown(store, id), /我的名称 100%_/)
  assert.match(conversationMarkdown(store, id), /生成中/)
  store.saveTool({ id: 'tool', sessionId: id, name: 'system_status', target: '', status: 'success', result: '{}', createdAt: new Date().toISOString() })
  store.deleteConversation(id)
  assert.equal(store.messages(id).length, 0)
  assert.equal(store.tools().length, 0)
  assert.equal(store.memories().length, 1)
  assert.equal(store.conversations().length, 1)
  assert.notEqual(store.get('selected'), id)
  assert.throws(() => store.deleteConversation(id))
  store.close()
})
test('空会话自定名称不被首条消息覆盖', () => {
  const store = new Store(':memory:'); const id = store.create()
  store.renameConversation(id, '自定名称'); store.add(id, 'user', '第一条', 'complete')
  assert.equal(store.conversations()[0].title, '自定名称'); store.close()
})
test('备份排除凭据权限，恢复新 ID/来源、中断状态、去重且保留现有设置', () => {
  const { store, id } = fixture()
  store.set('credential', 'PRIVATE_CREDENTIAL'); store.set('endpoint', 'PRIVATE_ENDPOINT')
  store.saveApp({ id: 'app', name: 'APP', target: 'PRIVATE_TARGET', approved: true, fingerprint: 'x' })
  const data = makeBackup(store), text = JSON.stringify(data)
  assert.doesNotMatch(text, /PRIVATE_|fingerprint|approved|credential/)
  const destination = new Store(':memory:'); destination.create(); destination.set('credential', 'LOCAL_KEY')
  const result = restoreBackup(destination, data)
  assert.deepEqual(result, { conversations: 1, messages: 2, memories: 1 })
  const restored = destination.conversations()[0]
  assert.notEqual(restored.id, id)
  const messages = destination.messages(restored.id)
  assert.equal(messages[1].status, 'interrupted')
  assert.equal(destination.memories()[0].source, '会话消息：' + messages[0].id)
  assert.equal(destination.get('credential'), 'LOCAL_KEY'); assert.equal(destination.apps().length, 0)
  assert.throws(() => restoreBackup(destination, { ...data, createdAt: new Date().toISOString() }), /已经恢复/)
  assert.equal(destination.conversations().length, 2)
  const again = makeBackup(destination)
  assert.doesNotThrow(() => parseBackup(JSON.stringify(again)))
  store.close(); destination.close()
})
test('备份严格检查版本、关联、重复 ID、类别、大小以及原子恢复失败', () => {
  const { store } = fixture(), data = makeBackup(store)
  for (const invalid of [null, {}, { ...data, version: 2 }, { ...data, credential: 'x' }, { ...data, conversations: [...data.conversations, ...data.conversations] }, { ...data, messages: [{ ...data.messages[0], sessionId: 'missing' }] }, { ...data, memories: [{ ...data.memories[0], category: 'unknown' }] }]) assert.throws(() => parseBackup(JSON.stringify(invalid)))
  assert.throws(() => parseBackup('{broken'))
  assert.throws(() => parseBackup(JSON.stringify({ ...data, messages: [...data.messages, data.messages[0]] })))
  assert.throws(() => parseBackup(JSON.stringify({ ...data, messages: [{ ...data.messages[0], role: 'system' }] })))
  assert.throws(() => parseBackup(JSON.stringify({ ...data, memories: [{ ...data.memories[0], content: 'x'.repeat(1001) }] })))
  const dest = new Store(':memory:'); dest.create()
  dest.db.exec("CREATE TRIGGER reject_message BEFORE INSERT ON messages BEGIN SELECT RAISE(ABORT,'test'); END")
  assert.throws(() => restoreBackup(dest, data))
  assert.equal(dest.conversations().length, 1); assert.equal(dest.memories().length, 0)
  dest.db.exec('DROP TRIGGER reject_message')
  dest.saveMemory({ content: data.memories[0].content, category: 'fact' })
  assert.equal(restoreBackup(dest, data).memories, 0)
  store.close(); dest.close()
})
test('记忆超额拒绝，事务失败不会部分导入', () => {
  const { store } = fixture(), dest = new Store(':memory:')
  for (let i = 0; i < 100; i++) dest.saveMemory({ content: '测试' + i, category: 'fact' })
  assert.throws(() => restoreBackup(dest, makeBackup(store)), /超过 100/)
  assert.equal(dest.conversations().length, 0)
  store.close(); dest.close()
})
